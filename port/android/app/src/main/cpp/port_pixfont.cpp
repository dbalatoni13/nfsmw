static int glyph_index(int c) {
    if (c >= 'a' && c <= 'z') c = c - 'a' + 'A';
    if (c < 32 || c > 90) return 0;
    return c - 32;
}

void port_pixfont_draw(float x, float y, float s, float r, float g, float b, const char *text) {
    float cx = x;
    const char *p;
    if (!text || s < 1.0f) s = 3.0f;
    for (p = text; *p; p++) {
        const unsigned char *rows = kFont[glyph_index((unsigned char)*p)];
        int row, col;
        for (row = 0; row < 7; row++) {
            unsigned char bits = rows[row];
            for (col = 0; col < 5; col++) {
                if (bits & (16 >> col)) {
                    float px = cx + (float)col * s;
                    float py = y + (float)row * s;
                    gx2d_quad(px, py, px + s, py + s, r, g, b, 1.0f);
                }
            }
        }
        cx += 6.0f * s;
    }
}
