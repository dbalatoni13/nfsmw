void Util::SetDefaultAzimuths(CHANPUB *pVoice) {
    const unsigned char *pAzimuths = gAzimuthFoldDownLut[gFoldDownTarget][pVoice->numchan - 1];
    for (int i = 0; i < pVoice->numchan; i++) {
        CHANPUB *pSourceVoice = &sndgs.chan[pVoice->voices[i]];
        pSourceVoice->azimuth = pAzimuths[i] << 8;
    }
}

